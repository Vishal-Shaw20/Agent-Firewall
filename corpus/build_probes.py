def page(title: str, body: str, inject: str = "", head_extra: str = "") -> str:
    return (f"<html><head><title>{title}</title>{head_extra}</head><body>"
            f"<h1>{title}</h1><p>{body}</p>{inject}"
            f"<p>Contact us through the form on this page.</p></body></html>")


